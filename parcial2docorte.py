# 1. Definición de Constantes (Rangos y Límites)
TemperaturaMinimaOptima = 18.0
TemperaturaMaximaOptima = 26.0
HumedadMinimaOptima = 60.0
HumedadMaximaOptima = 80.0

TemperaturaCriticaMinima = 12.0
TemperaturaCriticaMaxima = 32.0
HumedadCriticaMinima = 40.0
HumedadCriticaMaxima = 90.0

TemperaturaMinimaValida = -10.0
TemperaturaMaximaValida = 60.0
HumedadMinimaValida = 0.0
HumedadMaximaValida = 100.0

LimiteMaximoLecturas = 8

# 2. Inicialización de Variables de Control y Estadística
NumeroLectura = 0
SumaTemperaturas = 0.0
SumaHumedades = 0.0

# Valores extremos iniciales para el cálculo de mínimos y máximos
TemperaturaMinima = 1000.0
TemperaturaMaxima = -1000.0
HumedadMinima = 1000.0
HumedadMaxima = -1000.0

EstadoInvernadero = "Observación"
ResultadoFinal = ""
ListaTemperaturas = []
ListaHumedades = []

print("=== SISTEMA DE MONITOREO DE INVERNADERO ===")

# 3. Ciclo de repetición controlado (máximo 8 lecturas o hasta que se defina el estado final)
while NumeroLectura < LimiteMaximoLecturas:

    # Ciclo de validación de datos del sensor
    datoValido = False
    while not datoValido:
        try:
            TemperaturaActual = float(input(f"Lectura {NumeroLectura + 1} - Ingrese la temperatura (°C): "))
            HumedadActual = float(input(f"Lectura {NumeroLectura + 1} - Ingrese la humedad relativa (%): "))

            # Validar que los valores estén dentro de los rangos válidos del sensor
            if (TemperaturaMinimaValida <= TemperaturaActual <= TemperaturaMaximaValida) and \
               (HumedadMinimaValida <= HumedadActual <= HumedadMaximaValida):
                datoValido = True
            else:
                print("Dato inválido. Ingrese nuevamente la lectura (fuera del rango del sensor).")
        except ValueError:
            print("Error: Ingrese valores numéricos válidos.")

    # Incrementar contador de lecturas válidas
    NumeroLectura = NumeroLectura + 1

    # Actualizar acumuladores y listas con la secuencia
    SumaTemperaturas = SumaTemperaturas + TemperaturaActual
    SumaHumedades = SumaHumedades + HumedadActual
    ListaTemperaturas.append(TemperaturaActual)
    ListaHumedades.append(HumedadActual)

    # Actualizar mínimos y máximos registrados
    if TemperaturaActual < TemperaturaMinima:
        TemperaturaMinima = TemperaturaActual
    if TemperaturaActual > TemperaturaMaxima:
        TemperaturaMaxima = TemperaturaActual

    if HumedadActual < HumedadMinima:
        HumedadMinima = HumedadActual
    if HumedadActual > HumedadMaxima:
        HumedadMaxima = HumedadActual

    # 4. Evaluación de Estado y Toma de Decisiones

    # A. Prioridad 1: Verificar si algún valor alcanzó el límite crítico
    if (TemperaturaActual < TemperaturaCriticaMinima or TemperaturaActual > TemperaturaCriticaMaxima) or \
       (HumedadActual < HumedadCriticaMinima or HumedadActual > HumedadCriticaMaxima):
        EstadoInvernadero = "Crítico"
        ResultadoFinal = "Alerta crítica: activar protocolo de emergencia"
        break

    # B. Prioridad 2: Verificar si ambas variables están dentro del rango óptimo
    elif (TemperaturaMinimaOptima <= TemperaturaActual <= TemperaturaMaximaOptima) and \
         (HumedadMinimaOptima <= HumedadActual <= HumedadMaximaOptima):
        EstadoInvernadero = "Óptimo"
        if NumeroLectura == 1:
            ResultadoFinal = "Cultivo en condiciones óptimas"
        else:
            ResultadoFinal = "Cultivo estabilizado"
        break

    # C. Prioridad 3: Si alguna variable está fuera de lo óptimo (queda en observación)
    else:
        EstadoInvernadero = "Observación"
        print(f"Estado actual: {EstadoInvernadero}")
        print("Acción correctiva requerida:")

        if TemperaturaActual > TemperaturaMaximaOptima:
            print("- Ventilar")
        if TemperaturaActual < TemperaturaMinimaOptima:
            print("- Encender calefacción")
        if HumedadActual > HumedadMaximaOptima:
            print("- Deshumidificar")
        if HumedadActual < HumedadMinimaOptima:
            print("- Nebulizar (riego por neblina)")

        # Verificar si se completaron las 8 lecturas sin estabilizarse
        if NumeroLectura == LimiteMaximoLecturas:
            ResultadoFinal = "Revisión técnica de los equipos"
            break

# 5. Cálculo Final de Promedios
PromedioTemperatura = SumaTemperaturas / NumeroLectura
PromedioHumedad = SumaHumedades / NumeroLectura

# 6. Mostrar Resultados Finales Consolidados
print("\n" + "="*45)
print("INFORME FINAL DEL INVERNADERO")
print("="*45)
print(f"Resultado: {ResultadoFinal}. Lecturas tomadas: {NumeroLectura}.")
print(f"Temperatura: mínima {TemperaturaMinima} – máxima {TemperaturaMaxima} – promedio {PromedioTemperatura:.2f}.")
print(f"Humedad: mínima {HumedadMinima} – máxima {HumedadMaxima} – promedio {PromedioHumedad:.2f}.")
print(f"Secuencia de temperaturas: {'; '.join(map(str, ListaTemperaturas))}.")
print(f"Secuencia de humedades: {'; '.join(map(str, ListaHumedades))}.")